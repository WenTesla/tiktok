func TestGetFileType(t *testing.T) {
	// 真实常见 mp4 文件头：品牌 isom、box size 0x18（手机/录屏/剪辑最常用，此前会被误判为非 mp4）
	isom := []byte{0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d}
	assert.Equal(t, "mp4", GetFileType(isom))

	// 其它常见品牌也应识别为 mp4（此前均被拒）
	brands := [][]byte{
		{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x6d, 0x70, 0x34, 0x32}, // mp42
		{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x64, 0x61, 0x73, 0x68}, // dash
		{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x61, 0x76, 0x63, 0x31}, // avc1
		{0x00, 0x00, 0x00, 0x1c, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d}, // isom(size 0x1c)
	}
	for _, b := range brands {
		assert.Equal(t, "mp4", GetFileType(b), "品牌应识别为 mp4: %x", b)
	}

	// PDF 文件头魔数：%PDF-1.5（与 fileTypeMap 中存储的魔数一致）
	pdf := []byte("%PDF-1.5")
	assert.Equal(t, "pdf", GetFileType(pdf))

	// 普通文本不应被判为 mp4（GetFileType 是启发式，可能命中其它类型，这里只验证不是 mp4）
	assert.NotEqual(t, "mp4", GetFileType([]byte("hello world")))

	// 空输入返回空
	assert.Equal(t, "", GetFileType(nil))
	assert.Equal(t, "", GetFileType([]byte{}))
}

// TestIsVideo 验证常见视频容器能被识别，非视频文件应被拒绝。
func TestIsVideo(t *testing.T) {
	cases := []struct {
		name string
		head []byte
		want bool
	}{
		{"mp4-isom", []byte{0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d}, true},
		{"mp4-mp42", []byte{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x6d, 0x70, 0x34, 0x32}, true},
		{"mov-qt", []byte{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x71, 0x74, 0x20, 0x20}, true},
		{"webm", []byte{0x1A, 0x45, 0xDF, 0xA3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x77, 0x65, 0x62, 0x6d}, true},
		{"mkv", []byte{0x1A, 0x45, 0xDF, 0xA3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x6d, 0x61, 0x74}, true},
		{"flv", []byte{0x46, 0x4C, 0x56, 0x01, 0x05, 0x00, 0x00, 0x00, 0x09}, true},
		{"avi", []byte("RIFF\x00\x00\x00\x00AVI "), true},
		{"mpeg-ps", []byte{0x00, 0x00, 0x01, 0xBA, 0x44, 0x00, 0x00, 0x00}, true},
		{"mpeg-es", []byte{0x00, 0x00, 0x01, 0xB3, 0x00, 0x00, 0x00, 0x00}, true},
		{"wmv", []byte{0x30, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11, 0xA6, 0xD9}, true},
		{"rmvb", []byte{0x2E, 0x52, 0x4D, 0x46, 0x00, 0x00, 0x00, 0x12}, true},
		// 非视频：应被拒绝
		{"png", []byte{0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A}, false},
		{"pdf", []byte("%PDF-1.5"), false},
		{"text", []byte("hello world this is not a video"), false},
		{"empty", []byte{}, false},
	}
	for _, c := range cases {
		assert.Equal(t, c.want, IsVideo(c.head), "case %s", c.name)
	}
}

// TestVideoExt 验证扩展名推断：ftyp 按品牌区分 mp4/mov，其它容器各归其类。
func TestVideoExt(t *testing.T) {
	assert.Equal(t, "mp4", VideoExt([]byte{0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d}))
	assert.Equal(t, "mp4", VideoExt([]byte{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x6d, 0x70, 0x34, 0x32}))
	assert.Equal(t, "mov", VideoExt([]byte{0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x71, 0x74, 0x20, 0x20}))
	assert.Equal(t, "webm", VideoExt([]byte{0x1A, 0x45, 0xDF, 0xA3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x77, 0x65, 0x62, 0x6d}))
	assert.Equal(t, "mkv", VideoExt([]byte{0x1A, 0x45, 0xDF, 0xA3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x6d, 0x61, 0x74}))
	assert.Equal(t, "flv", VideoExt([]byte{0x46, 0x4C, 0x56, 0x01}))
	assert.Equal(t, "avi", VideoExt([]byte("RIFF\x00\x00\x00\x00AVI ")))
	assert.Equal(t, "mpg", VideoExt([]byte{0x00, 0x00, 0x01, 0xBA}))
	assert.Equal(t, "wmv", VideoExt([]byte{0x30, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11, 0xA6, 0xD9}))
	assert.Equal(t, "rmvb", VideoExt([]byte{0x2E, 0x52, 0x4D, 0x46}))
	// 无法识别时回退 mp4
	assert.Equal(t, "mp4", VideoExt([]byte("hello world this is not a video")))
}
